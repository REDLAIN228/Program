"""Three-pane studio assembled around the existing application's live controls."""
from PySide6.QtCore import Qt, QPropertyAnimation
from PySide6.QtWidgets import (QWidget, QVBoxLayout, QHBoxLayout, QLabel, QPushButton,
                               QFormLayout, QComboBox, QSpinBox, QSlider, QCheckBox,
                               QSplitter, QListWidget, QListWidgetItem, QStackedWidget,
                               QScrollArea, QGraphicsOpacityEffect)

from app.ui.common import Preview
from app.ui.instruments import TimerRing, icon, HoverAnimation


def button(text, action, parent_layout=None):
    widget = QPushButton(text)
    widget.clicked.connect(action)
    if parent_layout:
        parent_layout.addWidget(widget)
    return widget


def build_studio(p):
    old = p.takeCentralWidget()
    root = QWidget()
    layout = QVBoxLayout(root)
    layout.setContentsMargins(14, 12, 14, 12)
    layout.setSpacing(12)
    header = QHBoxLayout()
    brand = QLabel("ANIME DRAWER  <span style='color:#E73558'>2.0</span>")
    brand.setObjectName("brand")
    header.addWidget(brand)
    p.workspace_tagline = QLabel("PROFESSIONAL CREATIVE TOOL")
    header.addWidget(p.workspace_tagline)
    header.addStretch()
    header.addWidget(p.status)
    button("Свернуть", p.hide, header)
    layout.addLayout(header)
    splitter = QSplitter(Qt.Orientation.Horizontal)
    p.workspace_splitter = splitter
    p.navigation = QListWidget()
    p.navigation.setObjectName("navigation")
    p.navigation.setMinimumWidth(52)
    p.navigation.setMaximumWidth(190)
    entries = [("Dashboard", "dashboard"), ("AI Artist", "ai"), ("Image Import", "image"),
               ("Vector Engine", "vector"), ("Priority AI", "priority"),
               ("Drawing Settings", "settings"), ("History", "history"), ("Settings", "settings")]
    for label, glyph in entries:
        item = QListWidgetItem(icon(glyph), label)
        item.setToolTip(label)
        item.setData(Qt.ItemDataRole.UserRole, label)
        p.navigation.addItem(item)
    splitter.addWidget(p.navigation)
    center = QWidget()
    middle = QVBoxLayout(center)
    middle.setContentsMargins(8, 0, 8, 0)
    toolbar = QHBoxLayout()
    p.view_mode = QComboBox()
    p.view_mode.setSizeAdjustPolicy(QComboBox.SizeAdjustPolicy.AdjustToMinimumContentsLengthWithIcon)
    p.view_mode.setMinimumContentsLength(10)
    toolbar.addWidget(p.view_mode, 1)
    button("−", lambda: p.previews.currentWidget().zoom(1/1.2), toolbar)
    button("+", lambda: p.previews.currentWidget().zoom(1.2), toolbar)
    button("Fit", lambda: p.previews.currentWidget().fit_image(), toolbar)
    toolbar.addWidget(p.actions["PREVIEW"])
    middle.addLayout(toolbar)
    p.priority_view, p.vector_view, p.order_view = Preview(), Preview(), Preview()
    p.comparison_view, p.simulation_view = Preview(), Preview()
    for name, view in [("PRIORITY MAP", p.priority_view), ("VECTOR PREVIEW", p.vector_view),
                       ("STROKE ORDER", p.order_view), ("BEFORE / AFTER", p.comparison_view),
                       ("DRAWING SIMULATION", p.simulation_view)]:
        p.previews.addTab(view, name)
    p.view_mode.addItems([p.previews.tabText(i) for i in range(p.previews.count())])
    p.view_mode.currentIndexChanged.connect(p.previews.setCurrentIndex)
    p.previews.currentChanged.connect(p.view_mode.setCurrentIndex)
    p.previews.tabBar().hide()
    middle.addWidget(p.previews, 1)
    compare_row = QHBoxLayout()
    compare_row.addWidget(QLabel("Before / After"))
    p.before_after = QSlider(Qt.Orientation.Horizontal)
    p.before_after.setRange(0, 100)
    p.before_after.setValue(50)
    p.before_after.sliderMoved.connect(p.update_comparison)
    compare_row.addWidget(p.before_after, 1)
    p.simulate_button = button("▶ Simulation", p.prepare_simulation, compare_row)
    middle.addLayout(compare_row)
    middle.addWidget(p.progress)
    instruments = QHBoxLayout()
    p.timer_ring = TimerRing()
    p.timer_ring.setMaximumSize(165, 165)
    instruments.addWidget(p.timer_ring)
    summary = QVBoxLayout()
    summary.addWidget(p.stats)
    p.clock_stats = QLabel("Отсчёт синхронизируется вручную или начинается с RUN.")
    p.clock_stats.setWordWrap(True)
    summary.addWidget(p.clock_stats)
    p.log.setMaximumHeight(100)
    summary.addWidget(p.log)
    instruments.addLayout(summary, 1)
    middle.addLayout(instruments)
    splitter.addWidget(center)
    p.control_pages = QStackedWidget()
    p.control_pages.setMinimumWidth(282)
    p.control_pages.setMaximumWidth(370)
    forms = []
    for title in ("IMAGE & ARTIST", "VECTOR ENGINE", "DETAIL PRIORITY", "DRAW CONTROLS", "WORKSPACE"):
        page = QWidget()
        box = QVBoxLayout(page)
        label = QLabel(title)
        label.setObjectName("sectionTitle")
        box.addWidget(label)
        form = QFormLayout()
        form.setRowWrapPolicy(QFormLayout.RowWrapPolicy.WrapLongRows)
        box.addLayout(form)
        box.addStretch()
        scroll = QScrollArea()
        scroll.setWidgetResizable(True)
        scroll.setWidget(page)
        scroll.setFrameShape(QScrollArea.Shape.NoFrame)
        p.control_pages.addWidget(scroll)
        forms.append(form)
    f = forms[0]
    f.addRow("Источник", p.source)
    actions = QHBoxLayout()
    actions.addWidget(p.actions["IMPORT IMAGE"])
    actions.addWidget(p.actions["CAPTURE"])
    f.addRow(actions)
    f.addRow("Описание для AI", p.prompt)
    f.addRow(p.actions["GENERATE"])
    f.addRow("Стиль", p.style)
    f.addRow("Качество", p.quality)
    f.addRow(p.crop_fit)
    f.addRow(p.remove_bg)
    f.addRow(button("Обрезать изображение", p.crop_image))
    f.addRow(QLabel("Импорт и анализ работают локально.\nГенерация требует вашего AI API."))
    f = forms[1]
    p.engine = QComboBox()
    p.engine.addItems(["Vector 2.0", "Legacy"])
    p.vector_accuracy = QComboBox()
    p.vector_accuracy.addItems(["Speed", "Balanced", "Precision", "Ultra"])
    p.vector_accuracy.setCurrentText("Balanced")
    f.addRow("Движок", p.engine)
    f.addRow("Vector accuracy", p.vector_accuracy)
    f.addRow("Заполнение", p.brushwork)
    p.compare_button = button("OLD ENGINE / VECTOR 2.0", p.compare_engines)
    f.addRow(p.compare_button)
    p.vector_stats = QLabel("Постройте PREVIEW: здесь появятся число штрихов, точки, длина пути и оценка времени.")
    p.vector_stats.setWordWrap(True)
    f.addRow(p.vector_stats)
    f.addRow(button("Контуры", lambda: p.previews.setCurrentIndex(4)))
    f.addRow(button("Порядок штрихов", lambda: p.previews.setCurrentIndex(5)))
    f = forms[2]
    p.intelligence = QSlider(Qt.Orientation.Horizontal)
    p.intelligence.setRange(0, 100)
    p.intelligence.setValue(75)
    p.intelligence_label = QLabel("DETAIL INTELLIGENCE · 75%")
    f.addRow(p.intelligence_label)
    f.addRow(p.intelligence)
    p.priority_mode = QComboBox()
    p.priority_mode.addItems(["Auto", "Portrait", "Full Character", "Landscape", "Custom"])
    f.addRow("Композиция", p.priority_mode)
    p.detect_faces = QCheckBox("OpenCV лица / фигура · опционально")
    p.detect_faces.setChecked(True)
    f.addRow(p.detect_faces)
    p.region_score = QSpinBox()
    p.region_score.setRange(0, 100)
    p.region_score.setValue(100)
    f.addRow("Приоритет области", p.region_score)
    p.select_region = QPushButton("Выделить область на карте")
    p.select_region.setCheckable(True)
    p.select_region.toggled.connect(p.set_priority_selection)
    f.addRow(p.select_region)
    f.addRow(button("Удалить последнюю область", p.undo_priority_region))
    f.addRow(button("Сбросить ручные области", p.clear_priority_regions))
    f.addRow(button("Обновить PRIORITY MAP", p.analyze_priorities))
    p.priority_info = QLabel("Красный ≥85 · оранжевый ≥65\nжёлтый ≥40 · серый — низкий.\nСемантика тела/волос не распознаётся моделью; используется значимость и композиция.")
    p.priority_info.setWordWrap(True)
    f.addRow(p.priority_info)
    p.priority_view.region_selected.connect(p.add_priority_region)
    f = forms[3]
    f.addRow("Профиль", p.profile_combo)
    p.popup_profile = button("НОВЫЙ ПЛЕЙС · RGB v4 · 1366×768", p.install_popup_profile)
    f.addRow(p.popup_profile)
    p.ready_profile = button("ГОТОВЫЙ ПРОФИЛЬ · 1366×768", p.install_game_profile)
    f.addRow(p.ready_profile)
    pair = QHBoxLayout()
    pair.addWidget(p.actions["CALIBRATE"])
    pair.addWidget(p.actions["TEST DRAW"])
    f.addRow(pair)
    f.addRow(button("CHECK BRUSH SIZE", p.check_brush_size))
    f.addRow("Скорость", p.speed)
    p.game_delay = QSpinBox()
    p.game_delay.setRange(60, 1000)
    p.game_delay.setSuffix(" ms")
    p.game_delay.setValue(250)
    p.game_delay.setToolTip("Ожидание игры перед нажатием и после отпускания. При пропусках попробуйте 250–300 ms.")
    f.addRow("Задержка игры", p.game_delay)
    p.brush_opacity = QSpinBox()
    p.brush_opacity.setRange(1, 100)
    p.brush_opacity.setSuffix("%")
    p.brush_opacity.setValue(100)
    p.brush_opacity.setToolTip("Непрозрачность штрихов в игре. 100% сохраняет цвета; меньше — полупрозрачные штрихи с накоплением на пересечениях.")
    f.addRow("Непрозрачность", p.brush_opacity)
    p.brush_policy = QComboBox()
    p.brush_policy.addItems(["Auto", "Тонкая", "Средняя", "Широкая"])
    p.brush_policy.setToolTip("Используются только откалиброванные размеры. Тонкая и средняя ограничивают максимальную кисть.")
    f.addRow("Размер кисти", p.brush_policy)
    f.addRow("Формат", p.drawing_format)
    f.addRow("Масштаб", p.drawing_scale)
    pair = QHBoxLayout()
    pair.addWidget(p.drawing_width)
    pair.addWidget(QLabel("×"))
    pair.addWidget(p.drawing_height)
    f.addRow("Свой размер", pair)
    p.limit.clear()
    for label, value in [("Unlimited", None), ("30 seconds", 30), ("60 seconds", 60), ("90 seconds", 90),
                         ("120 seconds", 120), ("150 seconds", 150), ("165 seconds", 165),
                         ("180 seconds", 180), ("240 seconds", 240), ("300 seconds", 300),
                         ("Auto · 165 s", 165), ("Custom", "custom")]:
        p.limit.addItem(label, value)
    for label, value in p.settings.get("timer_presets", {}).items():
        p.limit.addItem(label, value)
    p.limit.setCurrentText("165 seconds")
    p.custom_time = QSpinBox()
    p.custom_time.setRange(1, 3600)
    p.custom_time.setSuffix(" s")
    p.custom_time.setValue(180)
    p.safety_buffer = QSpinBox()
    p.safety_buffer.setRange(0, 60)
    p.safety_buffer.setValue(8)
    p.safety_buffer.setSuffix(" s")
    p.smart_finish = QCheckBox("SMART FINISH MODE")
    p.smart_finish.setChecked(True)
    f.addRow("Drawing timer", p.limit)
    f.addRow("Custom", p.custom_time)
    f.addRow(button("Сохранить пресет таймера", p.save_timer_preset))
    f.addRow("Safety buffer", p.safety_buffer)
    f.addRow(p.smart_finish)
    f.addRow(button("Синхронизировать отсчёт", p.sync_round_clock))
    f.addRow(button("RESET TIMER", p.reset_round_clock))
    f = forms[4]
    p.overlay_enabled = QCheckBox("Виджет во время рисования")
    p.overlay_enabled.setToolTip("Разместите вне холста и инструментов. Перекрытие точки ввода останавливает рисование.")
    p.animations_enabled = QCheckBox("Плавные переходы")
    p.animations_enabled.setChecked(True)
    p.timer_ring.animation_enabled = p.animations_enabled.isChecked
    f.addRow(p.overlay_enabled)
    f.addRow(p.animations_enabled)
    f.addRow(button("AI API SETTINGS", p.ai_settings))
    f.addRow(button("LOCAL TEST CANVAS", p.open_test_canvas))
    f.addRow(button("DEBUG OVERLAY", p.show_debug))
    p.tools_button.setText("TOOLS · все команды")
    f.addRow(p.tools_button)
    splitter.addWidget(p.control_pages)
    splitter.setStretchFactor(1, 1)
    splitter.setSizes([164, 720, 330])
    layout.addWidget(splitter, 1)
    footer = QHBoxLayout()
    for widget in (p.run_button, p.pause_button, p.stop_button):
        footer.addWidget(widget)
    layout.addLayout(footer)
    p.setCentralWidget(root)
    old.deleteLater()
    p._advanced_controls = [p.engine, p.vector_accuracy, p.intelligence, p.priority_mode, p.detect_faces, p.brush_policy,
                            p.region_score, p.select_region, p.compare_button, p.simulate_button,
                            p.custom_time, p.safety_buffer, p.smart_finish, p.brush_opacity, p.game_delay,
                            p.ready_profile, p.popup_profile]
    def navigate(index):
        page = {0: 0, 1: 0, 2: 0, 3: 1, 4: 2, 5: 3, 7: 4}.get(index)
        if page is None:
            p.history()
            return
        p.control_pages.setCurrentIndex(page)
        if index == 4:
            p.previews.setCurrentIndex(3)
        if index == 3 and p.plan:
            p.previews.setCurrentIndex(4)
        if p.animations_enabled.isChecked():
            effect = QGraphicsOpacityEffect(p.control_pages)
            p.control_pages.setGraphicsEffect(effect)
            p._panel_animation = QPropertyAnimation(effect, b"opacity", p.control_pages)
            p._panel_animation.setDuration(150)
            p._panel_animation.setStartValue(.35)
            p._panel_animation.setEndValue(1.)
            p._panel_animation.start()
    p.navigation.currentRowChanged.connect(navigate)
    p.navigation.setCurrentRow(0)
    for control in (p.engine, p.vector_accuracy, p.priority_mode):
        control.currentTextChanged.connect(p.intelligence_changed)
    p.brush_policy.currentTextChanged.connect(p.invalidate_plan)
    p.brush_opacity.valueChanged.connect(p.invalidate_plan)
    p.game_delay.valueChanged.connect(p.invalidate_plan)
    p.intelligence.valueChanged.connect(p.intelligence_changed)
    p.detect_faces.toggled.connect(p.intelligence_changed)
    p.custom_time.valueChanged.connect(p.timer_changed)
    p.limit.currentTextChanged.connect(p.timer_changed)
    p.safety_buffer.valueChanged.connect(p.invalidate_plan)
    p.smart_finish.toggled.connect(p.invalidate_plan)
    p.overlay_enabled.toggled.connect(lambda value: p.save_setting("studio_overlay", value))
    p.animations_enabled.toggled.connect(lambda value: p.save_setting("studio_animations", value))
    p._hover_animations = [HoverAnimation(widget, p.animations_enabled.isChecked)
                           for widget in root.findChildren(QPushButton)]
